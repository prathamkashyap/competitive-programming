PROVIDERS = {
    "codeforces": codeforces.fetch_codeforces_stats,
    "leetcode": leetcode.fetch_leetcode_stats,
    "codechef": codechef.fetch_codechef_stats,
    "hackerearth": hackerearth.fetch_hackerearth_stats,
    "hackerrank": hackerrank.fetch_hackerrank_stats,
    "geeksforgeeks": geeksforgeeks.fetch_geeksforgeeks_stats,
    "atcoder": atcoder.fetch_atcoder_stats,
    "cses": cses.fetch_cses_stats,
}


def fetch_all_external_stats(repo_root: Path) -> List[PlatformStats]:
    """
    Fetch statistics for all configured platforms discovered in repository.

    Args:
        repo_root: Path to the repository root

    Returns:
        List of PlatformStats for all platforms
    """
    profile_info = get_profile_info(repo_root)
    results = []

    # Desired order for canonical output
    platform_order = ["leetcode", "codeforces", "codechef", "hackerrank", "hackerearth", "geeksforgeeks"]

    # Sort discovered platforms to match canonical order, followed by any others
    ordered_keys = [p for p in platform_order if p in profile_info] + [p for p in profile_info if p not in platform_order]

    for platform in ordered_keys:
        info = profile_info[platform]
        username = info["username"]
        profile_url = info["profile_url"]

        provider = PROVIDERS.get(platform)

        if provider is None:
            results.append(
                PlatformStats(
                    platform=platform.capitalize(),
                    username=username,
                    profile_url=profile_url,
                    status=RetrievalStatus.UNCONFIGURED,
                    error=f"No provider available for {platform}",
                    source="none",
                )
            )
            continue

        try:
            stats = provider(username, profile_url)

            # If live retrieval failed or was unavailable, try snapshot fallback
            if stats.status in [RetrievalStatus.UNAVAILABLE, RetrievalStatus.FAILED]:
                snapshot_stats = get_snapshot_stats(platform, username, profile_url)
                if snapshot_stats:
                    results.append(snapshot_stats)
                else:
                    results.append(stats)
            else:
                # If live succeeded or partial, check if snapshot can supplement any dashboard-only metrics
                snapshot_stats = get_snapshot_stats(platform, username, profile_url)
                if snapshot_stats and snapshot_stats.metrics:
                    # Supplement non-conflicting metrics (like dashboard streaks)
                    for k, v in snapshot_stats.metrics.items():
                        if k not in stats.metrics:
                            stats.metrics[k] = v

                results.append(stats)

        except Exception as e:
            # If provider threw uncaught exception, attempt snapshot fallback
            snapshot_stats = get_snapshot_stats(platform, username, profile_url)
            if snapshot_stats:
                results.append(snapshot_stats)
            else:
                results.append(
                    PlatformStats(
                        platform=platform.capitalize(),
                        username=username,
                        profile_url=profile_url,
                        status=RetrievalStatus.FAILED,
                        error=f"Provider error: {str(e)}",
                        source="provider",
                    )
                )

    return results


def generate_external_stats_json(results: List[PlatformStats], output_path: Path):
    """
    Generate external-stats.json from platform statistics.
    """
    data = [stats.to_dict() for stats in results]
    with open(output_path, "w", encoding="utf-8") as f:
        json.dump(data, f, indent=2)


def generate_external_stats_markdown(results: List[PlatformStats], output_path: Path):
    """
    Generate rich external-stats.md from platform statistics.
    """
    lines = [
        "# 🌐 External Platform Profile Statistics",
        "",
        "<!--",
        "This file is automatically generated by scripts/external_stats.py.",
        "Do not edit this file manually.",
        "To update external statistics, run: python scripts/external_stats.py",
        "-->",
        "",
        "Live and verified statistics from external competitive programming and algorithmic practice platforms.",
        "These metrics represent verified activity across official APIs, public GraphQL endpoints, and structured profiles.",
        "",
        "> [!NOTE]",
        "> External statistics reflect platform-specific activity and are maintained independently from the repository's local solution files.",
        "> Solved counts are reported individually per platform and are not aggregated into a misleading total.",
        "",
        "---",
        "",
        "## 📊 Platform Summary",
        "",
        "| Platform | Handle | Status | Source Type | Method | Key Highlights |",
        "| :--- | :--- | :---: | :---: | :--- | :--- |",
    ]

    for s in results:
        status_badge = {
            RetrievalStatus.SUCCESS: "✅ `success`",
            RetrievalStatus.PARTIAL: "🟡 `partial`",
            RetrievalStatus.UNAVAILABLE: "⚪ `unavailable`",
            RetrievalStatus.UNCONFIGURED: "⚙️ `unconfigured`",
            RetrievalStatus.FAILED: "❌ `failed`",
        }.get(s.status, f"`{s.status.value}`")

        source_type_badge = "🟢 `live`" if s.source_type == "live" else "📸 `snapshot`"
        highlights = _format_platform_highlights(s.platform, s.metrics)

        lines.append(
            f"| **[{s.platform}]({s.profile_url})** | `{s.username}` | {status_badge} | {source_type_badge} | `{s.retrieval_method}` | {highlights} |"
        )

    lines.extend([
        "",
        "---",
        "",
        "## 🔍 Detailed Platform Profiles",
        "",
    ])

    for s in results:
        if s.status in [RetrievalStatus.SUCCESS, RetrievalStatus.PARTIAL]:
            lines.extend(_format_platform_detail_section(s))

    # Unavailable or Failed
    unsuccessful = [s for s in results if s.status in [RetrievalStatus.UNAVAILABLE, RetrievalStatus.FAILED, RetrievalStatus.UNCONFIGURED]]
    if unsuccessful:
        lines.extend([
            "---",
            "",
            "## ⚠️ Unavailable or Unconfigured Platforms",
            "",
        ])
        for s in unsuccessful:
            lines.append(f"- **{s.platform}**: {s.error or 'No public metrics accessible'}")
        lines.append("")

    lines.extend([
        "---",
        "",
        "## 📖 Methodology & Data Philosophy",
        "",
        "- **Public Structured Data First**: We query official APIs, public GraphQL endpoints (`leetcode.com/graphql`), and REST APIs (`hackerrank.com/rest/hackers/`) rather than fragile text scraping.",
        "- **Semantic Verification**: Star ratings, percentiles, solved categories, and ranks are mapped directly to their actual schema definitions.",
        "- **Live vs Snapshot Transparency**: Live data is queried directly; verified screenshots are used as immutable baseline snapshots when live endpoints are shielded.",
        "- **No Misleading Solved Sums**: Problem overlaps between platforms prevent calculating a mathematically sound single 'total unique solved' number; platform numbers are kept distinct and verifiable.",
        "- **Repository Separation**: Local repository file statistics (file counts, lines of code, test passes) are tracked separately in [stats.md](stats.md).",
        "",
    ])

    with open(output_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))


def _format_platform_highlights(platform: str, m: Dict[str, Any]) -> str:
    """Return a concise highlight string for the summary table."""
    p = platform.lower()
    if p == "leetcode":
        solved = m.get("solved", "—")
        acc = f"{m['acceptance_rate']}% AC" if "acceptance_rate" in m else ""
        streak = f"{m['streak_days']}d streak" if "streak_days" in m else ""
        parts = [f"**{solved}** solved", acc, streak]
        return ", ".join([p for p in parts if p])
    elif p == "codeforces":
        rating = m.get("rating", "—")
        rank = m.get("rank", "")
        solved = f"{m['solved']} solved" if "solved" in m else ""
        return f"Rating **{rating}** ({rank}), {solved}"
    elif p == "codechef":
        rating = m.get("rating", "—")
        league = m.get("league", "")
        dsa = f"DSA **{m['dsa_rating']}**" if "dsa_rating" in m else ""
        solved = f"{m['solved']} solved" if "solved" in m else ""
        parts = [f"Rating **{rating}**", league, dsa, solved]
        return ", ".join([p for p in parts if p])
    elif p == "hackerrank":
        ps_stars = f"Problem Solving **{m.get('problem_solving_stars', '—')}★**"
        tot_stars = f"**{m.get('total_stars', '—')}** total stars"
        solved = f"**{m.get('total_challenges_solved', '—')}** solved"
        return f"{ps_stars}, {tot_stars}, {solved}"
    elif p == "hackerearth":
        pts = f"**{m.get('points', '—')}** pts"
        solved = f"**{m.get('solved', '—')}** solved"
        rank = f"BP #{m['basic_programming_rank']}" if "basic_programming_rank" in m else ""
        return f"{pts}, {solved}, {rank}"
    elif p == "geeksforgeeks":
        score = f"Score **{m.get('coding_score', '—')}**"
        solved = f"**{m.get('solved', '—')}** solved"
        streak = f"{m.get('longest_streak_days', '—')}d streak" if "longest_streak_days" in m else ""
        return f"{score}, {solved}, {streak}"
    return "Active Profile"


